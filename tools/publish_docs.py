#!/usr/bin/env python3
"""
publish_docs.py

Generate the public documentation for wg_manager and publish it to GitHub.

Pipeline:

    project source
        |
        +--> project_index.py
        |
        +--> protocol_flow.py src/wg_auth
        +--> protocol_flow.py src/wg_client
        +--> protocol_flow.py src/wg_manager
        |
        +--> docs/
                |
                +--> validation
                |
                +--> temporary git staging repository
                        |
                        +--> commit
                        +--> push
                        +--> GitHub Pages

The project itself does NOT need to be a Git repository.

Only the generated docs/ tree is published.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

GITHUB_REPO = "manzosgorgo/wg-manager-docs"

PROTOCOLS = {
    "wg_auth": "src/wg_auth",
    "wg_client": "src/wg_client",
    "wg_manager": "src/wg_manager",
    "wg_all": "src",
}

PROTOCOL_OUTPUTS = {
    "wg_auth": "wg_auth_proto.md",
    "wg_client": "wg_client_proto.md",
    "wg_manager": "wg_manager_proto.md",
    "wg_all": "wg_all_proto.md",
}

PRIVATE_KEY_MARKERS = (
    "-----BEGIN PRIVATE KEY-----",
    "-----BEGIN RSA PRIVATE KEY-----",
    "-----BEGIN EC PRIVATE KEY-----",
    "-----BEGIN OPENSSH PRIVATE KEY-----",
)


# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

SCRIPT_PATH = Path(__file__).resolve()
PROJECT_ROOT = SCRIPT_PATH.parent.parent
TOOLS_DIR = PROJECT_ROOT / "tools"
DOCS_DIR = PROJECT_ROOT / "docs"
AI_DIR = DOCS_DIR / "ai"

PROJECT_INDEX = TOOLS_DIR / "project_index.py"
PROTOCOL_FLOW = TOOLS_DIR / "protocol_flow.py"


# ---------------------------------------------------------------------------
# Utility functions
# ---------------------------------------------------------------------------

def run(
    command: list[str],
    *,
    cwd: Path | None = None,
    capture: bool = False,
) -> subprocess.CompletedProcess[str]:
    """Run a command and fail loudly on errors."""

    print("$", " ".join(command))

    return subprocess.run(
        command,
        cwd=cwd,
        check=True,
        text=True,
        capture_output=capture,
    )


def command_exists(command: str) -> bool:
    return shutil.which(command) is not None


def fail(message: str) -> "NoReturn":
    print(f"\nERROR: {message}", file=sys.stderr)
    raise SystemExit(1)


# ---------------------------------------------------------------------------
# Documentation generation
# ---------------------------------------------------------------------------

def clean_obsolete_generated_site() -> None:
    """
    Remove the old HTML site generated by build_docs.py.

    We deliberately do not recursively delete arbitrary HTML files because
    source HTML files may legitimately be part of the project documentation.
    """

    old_site = DOCS_DIR / "site"

    if old_site.exists():
        print(f"Removing obsolete generated site: {old_site}")
        shutil.rmtree(old_site)

    # Old generated landing page. The public documentation is now Markdown.
    old_index = DOCS_DIR / "index.html"

    if old_index.exists():
        print(f"Removing obsolete generated index: {old_index}")
        old_index.unlink()


def generate_project_index() -> None:
    print("\n[1/6] Generating project index")

    if not PROJECT_INDEX.is_file():
        fail(f"project_index.py not found: {PROJECT_INDEX}")

    run(
        [
            sys.executable,
            str(PROJECT_INDEX),
            str(PROJECT_ROOT),
            "--output",
            str(AI_DIR),
            "--clean",
        ],
        cwd=PROJECT_ROOT,
    )


def generate_protocol(name: str, source_relative: str) -> None:
    """
    Run protocol_flow.py with the component directory itself as the repo root.

    protocol_flow.py writes its Markdown report to stdout, so stdout becomes
    the generated protocol snapshot.
    """

    print(f"\nGenerating protocol snapshot: {name}")

    source_root = PROJECT_ROOT / source_relative
    output_name = PROTOCOL_OUTPUTS[name]
    output_path = AI_DIR / output_name

    if not source_root.is_dir():
        fail(f"Protocol source directory does not exist: {source_root}")

    result = run(
        [
            sys.executable,
            str(PROTOCOL_FLOW),
            str(source_root),
            "--no-tests",
        ],
        cwd=PROJECT_ROOT,
        capture=True,
    )

    output = result.stdout

    if not output.strip():
        fail(
            f"protocol_flow.py produced empty output for {name}: "
            f"{source_root}"
        )

    output_path.write_text(output, encoding="utf-8")

    print(f"  -> {output_path}")


def generate_protocol_snapshots() -> None:
    print("\n[2/6] Generating protocol snapshots")

    if not PROTOCOL_FLOW.is_file():
        fail(f"protocol_flow.py not found: {PROTOCOL_FLOW}")

    AI_DIR.mkdir(parents=True, exist_ok=True)

    for name, source_relative in PROTOCOLS.items():
        generate_protocol(name, source_relative)


