def github_repo_exists() -> bool:
    result = subprocess.run(
        [
            "gh",
            "repo",
            "view",
            GITHUB_REPO,
        ],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    return result.returncode == 0


def ensure_github_repo() -> None:
    print("\nChecking GitHub repository")

    if github_repo_exists():
        print(f"GitHub repository exists: {GITHUB_REPO}")
        return

    print(f"Creating public GitHub repository: {GITHUB_REPO}")

    run(
        [
            "gh",
            "repo",
            "create",
            GITHUB_REPO,
            "--public",
        ],
        cwd=PROJECT_ROOT,
    )


def get_default_branch() -> str:
    result = run(
        [
            "gh",
            "repo",
            "view",
            GITHUB_REPO,
            "--json",
            "defaultBranchRef",
            "--jq",
            ".defaultBranchRef.name",
        ],
        cwd=PROJECT_ROOT,
        capture=True,
    )

    branch = result.stdout.strip()

    # An empty repository may not have a default branch yet.
    return branch or "main"


# ---------------------------------------------------------------------------
# Staging
# ---------------------------------------------------------------------------

def copy_docs_to_staging(staging: Path) -> None:
    """
    Make staging contain exactly the contents of docs/.
    """

    for item in staging.iterdir():
        if item.name == ".git":
            continue

        if item.is_dir():
            shutil.rmtree(item)
        else:
            item.unlink()

    for item in DOCS_DIR.iterdir():
        destination = staging / item.name

        if item.is_dir():
            shutil.copytree(item, destination)
        else:
            shutil.copy2(item, destination)


def prepare_staging(staging: Path, branch: str) -> None:
    """
    Prepare a complete Git repository in the temporary staging directory.

    If the remote already has history, clone it.

    If the remote repository is empty, initialize it locally.
    """

    remote = f"https://github.com/{GITHUB_REPO}.git"

    # Try cloning first. This handles normal existing repositories.
    clone_result = subprocess.run(
        [
            "git",
            "clone",
            remote,
            str(staging),
        ],
        cwd=PROJECT_ROOT,
        text=True,
        capture_output=True,
    )

    if clone_result.returncode != 0:
        # Empty repositories cannot always be cloned depending on their
        # current GitHub state. Initialize a fresh repository instead.
        print("Remote repository has no usable history; initializing staging.")

        run(
            [
                "git",
                "init",
                "-b",
                branch,
            ],
            cwd=staging,
        )

        run(
            [
                "git",
                "remote",
                "add",
                "origin",
                remote,
            ],
            cwd=staging,
        )
    else:
        # The clone created the directory and its .git.
        pass


def configure_git_identity(staging: Path) -> None:
    """
    Configure a local identity only if Git does not already have one.

    We use GitHub's noreply identity so the publisher does not depend on
    the user's global Git configuration.
    """

    email = subprocess.run(
        ["git", "config", "--get", "user.email"],
        cwd=staging,
        text=True,
        capture_output=True,
    )

    name = subprocess.run(
        ["git", "config", "--get", "user.name"],
        cwd=staging,
        text=True,
        capture_output=True,
    )

    if not email.stdout.strip():
        run(
            [
                "git",
                "config",
                "user.email",
                "41898282+github-actions[bot]@users.noreply.github.com",
            ],
            cwd=staging,
        )

    if not name.stdout.strip():
        run(
            [
                "git",
                "config",
                "user.name",
                "wg-manager documentation publisher",
            ],
            cwd=staging,
        )


def stage_docs(staging: Path) -> None:
    copy_docs_to_staging(staging)

    run(
        [
            "git",
            "add",
            "--all",
        ],
        cwd=staging,
    )


def has_staged_changes(staging: Path) -> bool:
    result = subprocess.run(
        [
            "git",
            "diff",
            "--cached",
            "--quiet",
        ],
        cwd=staging,
    )

    return result.returncode != 0


def commit_and_push(staging: Path, branch: str) -> bool:
    """
    Commit and push.

    Returns True when something was pushed, False when documentation was
    already up to date.
    """

    if not has_staged_changes(staging):
        print("\nDocumentation unchanged; nothing to commit or push.")
        return False

    run(
        [
            "git",
            "commit",
            "-m",
            "Update generated documentation",
        ],
        cwd=staging,
    )

    # For an initialized empty repository, establish the branch.
    run(
        [
            "git",
            "branch",
            "-M",
            branch,
        ],
        cwd=staging,
    )

    run(
        [
            "git",
            "push",
            "--set-upstream",
            "origin",
            branch,
        ],
        cwd=staging,
    )

    return True


