def validate_required_files() -> None:
    print("\n[4/6] Validating generated documentation")

    required = [
        DOCS_DIR / "README.md",
        AI_DIR / "README.md",
        AI_DIR / "TREE.md",
        AI_DIR / "MODULES.md",
        AI_DIR / "DEPENDENCIES.md",
        AI_DIR / "SYMBOLS.md",
        AI_DIR / "CONNECTIONS.md",
        AI_DIR / "wg_auth_proto.md",
        AI_DIR / "wg_client_proto.md",
        AI_DIR / "wg_manager_proto.md",
        AI_DIR / "wg_all_proto.md",
    ]

    missing = [path for path in required if not path.is_file()]

    if missing:
        for path in missing:
            print(f"  missing: {path}", file=sys.stderr)

        fail("documentation validation failed")


def validate_no_private_keys() -> None:
    """
    Second safety barrier against accidentally publishing key material.

    project_index.py already excludes sensitive source files. This scan is
    intentionally independent of that mechanism.
    """

    suspicious = []

    for path in DOCS_DIR.rglob("*"):
        if not path.is_file():
            continue

        # Ignore binary-looking files.
        try:
            data = path.read_bytes()
        except OSError:
            continue

        for marker in PRIVATE_KEY_MARKERS:
            if marker.encode("utf-8") in data:
                suspicious.append((path, marker))

    if suspicious:
        print(
            "\nPossible private key material found:",
            file=sys.stderr,
        )

        for path, marker in suspicious:
            print(f"  {path}: {marker}", file=sys.stderr)

        fail("refusing to publish possible private key material")


def validate_no_obsolete_site() -> None:
    old_site = DOCS_DIR / "site"

    if old_site.exists():
        fail(f"obsolete HTML site still exists: {old_site}")


def validate_docs() -> None:
    validate_required_files()
    validate_no_private_keys()
    validate_no_obsolete_site()

    print("Documentation validation: OK")


# ---------------------------------------------------------------------------
# GitHub repository
