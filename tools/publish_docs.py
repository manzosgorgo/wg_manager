# GitHub Pages
# ---------------------------------------------------------------------------

def configure_pages(branch: str) -> None:
    """
    Configure GitHub Pages to publish the root of the default branch.

    The repository itself remains Markdown-first. GitHub Pages/Jekyll can
    render the Markdown files as a web site.
    """

    print("\nConfiguring GitHub Pages")

    # First inspect current Pages configuration.
    result = subprocess.run(
        [
            "gh",
            "api",
            f"/repos/{GITHUB_REPO}/pages",
        ],
        cwd=PROJECT_ROOT,
        text=True,
        capture_output=True,
    )

    if result.returncode == 0:
        print("GitHub Pages already configured.")

        # Try to update it to the desired source.
        update = subprocess.run(
            [
                "gh",
                "api",
                "--method",
                "PUT",
                f"/repos/{GITHUB_REPO}/pages",
                "-f",
                f"source[branch]={branch}",
                "-f",
                "source[path]=/",
            ],
            cwd=PROJECT_ROOT,
            text=True,
            capture_output=True,
        )

        if update.returncode == 0:
            print(f"GitHub Pages source: {branch}:/")
        else:
            print(
                "Warning: existing Pages configuration could not be updated.",
                file=sys.stderr,
            )

        return

    # Pages is not configured yet.
    create = subprocess.run(
        [
            "gh",
            "api",
            "--method",
            "POST",
            f"/repos/{GITHUB_REPO}/pages",
            "-f",
            f"source[branch]={branch}",
            "-f",
            "source[path]=/",
        ],
        cwd=PROJECT_ROOT,
        text=True,
        capture_output=True,
    )

    if create.returncode != 0:
        print(
            "Warning: GitHub Pages could not be configured automatically.",
            file=sys.stderr,
        )
        print(create.stderr, file=sys.stderr)
        return

    print(f"GitHub Pages configured from {branch}:/")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate and publish wg_manager documentation."
    )

    parser.add_argument(
        "--repo",
        default=GITHUB_REPO,
        help=f"GitHub repository (default: {GITHUB_REPO})",
    )

    parser.add_argument(
        "--no-push",
        action="store_true",
        help="Generate and validate documentation but do not push.",
    )

    parser.add_argument(
        "--no-pages",
        action="store_true",
        help="Do not configure GitHub Pages.",
    )

    return parser.parse_args()


def main() -> int:
    global GITHUB_REPO

    args = parse_args()
    GITHUB_REPO = args.repo

    print("=" * 72)
    print("wg-manager documentation publisher")
    print("=" * 72)
    print(f"Project : {PROJECT_ROOT}")
    print(f"Docs    : {DOCS_DIR}")
    print(f"GitHub  : {GITHUB_REPO}")

    if not command_exists("git"):
        fail("git command not found")

    if not command_exists("gh"):
        fail("gh command not found")

    if not PROJECT_ROOT.is_dir():
        fail(f"project root does not exist: {PROJECT_ROOT}")

    if not TOOLS_DIR.is_dir():
        fail(f"tools directory does not exist: {TOOLS_DIR}")

    DOCS_DIR.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # Generate
    # ------------------------------------------------------------------

    clean_obsolete_generated_site()

    generate_project_index()
    generate_protocol_snapshots()
    generate_readme()

    # ------------------------------------------------------------------
    # Validate
    # ------------------------------------------------------------------

    validate_docs()

    if args.no_push:
        print("\n--no-push specified; stopping after documentation generation.")
        return 0

    # ------------------------------------------------------------------
    # GitHub
    # ------------------------------------------------------------------

    ensure_github_repo()

    branch = get_default_branch()

    print(f"\nUsing GitHub default branch: {branch}")

    # ------------------------------------------------------------------
    # Temporary staging repository
    # ------------------------------------------------------------------

    print("\n[5/6] Preparing temporary Git staging area")

    with tempfile.TemporaryDirectory(
        prefix="wg-manager-docs-publish-"
    ) as temp_dir:

        staging = Path(temp_dir) / "repo"

        prepare_staging(staging, branch)
        configure_git_identity(staging)

        stage_docs(staging)

        pushed = commit_and_push(staging, branch)

    # ------------------------------------------------------------------
    # Pages
    # ------------------------------------------------------------------

    if not args.no_pages:
        configure_pages(branch)

    print("\n[6/6] Publication complete")

    if pushed:
        print(f"Published: https://github.com/{GITHUB_REPO}")
    else:
        print("Remote documentation was already up to date.")

    if not args.no_pages:
        print(
            "Pages:",
            f"https://{GITHUB_REPO.split('/')[0]}.github.io/"
            f"{GITHUB_REPO.split('/')[1]}/",
        )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
